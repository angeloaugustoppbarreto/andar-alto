-- =====================================================================
-- Andar Alto - esquema do banco de dados (versão 1)
--
-- Este arquivo é o "mapa" do banco. O Flyway executa os arquivos
-- V1__, V2__... em ordem, uma única vez cada, e registra o que já rodou.
-- Assim o banco evolui de forma controlada (nunca edite uma versão
-- que já foi aplicada: crie a próxima, por exemplo V3__...).
--
-- Escrito em SQL padrão: funciona no H2 (usado aqui) e no PostgreSQL.
-- =====================================================================

-- ---------------------------------------------------------------------
-- USUARIOS: quem acessa o sistema. O campo "perfil" define o que cada
-- pessoa pode fazer: COMPRADOR, VENDEDOR ou ADMIN.
-- A senha NUNCA é guardada em texto puro: apenas o hash BCrypt.
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    telefone    VARCHAR(20),
    perfil      VARCHAR(20)  NOT NULL,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuarios_email  UNIQUE (email),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('COMPRADOR', 'VENDEDOR', 'ADMIN'))
);

-- ---------------------------------------------------------------------
-- APARTAMENTOS: os anúncios. Cada um pertence a um vendedor (usuario).
-- O "status" controla o ciclo de vida do anúncio:
--   EM_ANALISE -> PUBLICADO -> RESERVADO -> VENDIDO
--   (REJEITADO e PAUSADO são desvios do caminho principal)
-- ---------------------------------------------------------------------
CREATE TABLE apartamentos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendedor_id       BIGINT        NOT NULL,
    titulo            VARCHAR(140)  NOT NULL,
    descricao         VARCHAR(4000) NOT NULL,
    preco             NUMERIC(14,2) NOT NULL,
    valor_condominio  NUMERIC(10,2),
    area_m2           INTEGER       NOT NULL,
    quartos           INTEGER       NOT NULL,
    suites            INTEGER       NOT NULL DEFAULT 0,
    banheiros         INTEGER       NOT NULL,
    vagas             INTEGER       NOT NULL DEFAULT 0,
    andar             INTEGER,
    cep               VARCHAR(9),
    logradouro        VARCHAR(160)  NOT NULL,
    numero            VARCHAR(10),
    bairro            VARCHAR(80)   NOT NULL,
    cidade            VARCHAR(80)   NOT NULL,
    uf                VARCHAR(2)    NOT NULL,
    status            VARCHAR(20)   NOT NULL DEFAULT 'EM_ANALISE',
    motivo_rejeicao   VARCHAR(500),
    destaque          BOOLEAN       NOT NULL DEFAULT FALSE,
    criado_em         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_apartamentos_vendedor FOREIGN KEY (vendedor_id) REFERENCES usuarios (id),
    CONSTRAINT ck_apartamentos_preco    CHECK (preco > 0),
    CONSTRAINT ck_apartamentos_status   CHECK (status IN
        ('EM_ANALISE', 'PUBLICADO', 'REJEITADO', 'RESERVADO', 'VENDIDO', 'PAUSADO'))
);
CREATE INDEX idx_apartamentos_status   ON apartamentos (status);
CREATE INDEX idx_apartamentos_cidade   ON apartamentos (cidade);
CREATE INDEX idx_apartamentos_vendedor ON apartamentos (vendedor_id);

-- ---------------------------------------------------------------------
-- COMODIDADES (piscina, academia...) e a tabela de ligação N:N.
-- Um apartamento tem várias comodidades, e uma comodidade serve a vários
-- apartamentos. Relações N:N sempre precisam de uma tabela no meio.
-- ---------------------------------------------------------------------
CREATE TABLE comodidades (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(60) NOT NULL,
    CONSTRAINT uk_comodidades_nome UNIQUE (nome)
);

CREATE TABLE apartamento_comodidades (
    apartamento_id  BIGINT NOT NULL,
    comodidade_id   BIGINT NOT NULL,
    PRIMARY KEY (apartamento_id, comodidade_id),
    CONSTRAINT fk_apcom_apartamento FOREIGN KEY (apartamento_id) REFERENCES apartamentos (id) ON DELETE CASCADE,
    CONSTRAINT fk_apcom_comodidade  FOREIGN KEY (comodidade_id)  REFERENCES comodidades (id)  ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- IMAGENS do anúncio (1:N). Aqui guardamos só o endereço (url) da imagem.
-- Neste projeto as imagens são ilustrações fictícias geradas pelo sistema.
-- ---------------------------------------------------------------------
CREATE TABLE apartamento_imagens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartamento_id  BIGINT       NOT NULL,
    url             VARCHAR(255) NOT NULL,
    legenda         VARCHAR(80),
    ordem           INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT fk_imagens_apartamento FOREIGN KEY (apartamento_id) REFERENCES apartamentos (id) ON DELETE CASCADE
);
CREATE INDEX idx_imagens_apartamento ON apartamento_imagens (apartamento_id);

-- ---------------------------------------------------------------------
-- FAVORITOS (N:N entre comprador e apartamento).
-- ---------------------------------------------------------------------
CREATE TABLE favoritos (
    usuario_id      BIGINT    NOT NULL,
    apartamento_id  BIGINT    NOT NULL,
    criado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, apartamento_id),
    CONSTRAINT fk_fav_usuario     FOREIGN KEY (usuario_id)     REFERENCES usuarios (id)     ON DELETE CASCADE,
    CONSTRAINT fk_fav_apartamento FOREIGN KEY (apartamento_id) REFERENCES apartamentos (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- PROPOSTAS: o comprador oferece um valor por um apartamento.
-- Status: PENDENTE -> ACEITA | RECUSADA | CANCELADA
-- ---------------------------------------------------------------------
CREATE TABLE propostas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartamento_id  BIGINT        NOT NULL,
    comprador_id    BIGINT        NOT NULL,
    valor_ofertado  NUMERIC(14,2) NOT NULL,
    mensagem        VARCHAR(1000),
    status          VARCHAR(20)   NOT NULL DEFAULT 'PENDENTE',
    resposta        VARCHAR(500),
    criado_em       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    respondido_em   TIMESTAMP,
    CONSTRAINT fk_propostas_apartamento FOREIGN KEY (apartamento_id) REFERENCES apartamentos (id),
    CONSTRAINT fk_propostas_comprador   FOREIGN KEY (comprador_id)   REFERENCES usuarios (id),
    CONSTRAINT ck_propostas_valor       CHECK (valor_ofertado > 0),
    CONSTRAINT ck_propostas_status      CHECK (status IN ('PENDENTE', 'ACEITA', 'RECUSADA', 'CANCELADA'))
);
CREATE INDEX idx_propostas_apartamento ON propostas (apartamento_id, status);
CREATE INDEX idx_propostas_comprador   ON propostas (comprador_id);

-- ---------------------------------------------------------------------
-- VENDAS: registro da venda concluída (um apartamento só é vendido uma
-- vez: por isso apartamento_id e proposta_id são UNIQUE).
-- Guardamos o percentual e o valor da comissão da plataforma NO MOMENTO
-- da venda, para o histórico não mudar se a taxa mudar depois.
-- ---------------------------------------------------------------------
CREATE TABLE vendas (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartamento_id       BIGINT        NOT NULL,
    proposta_id          BIGINT        NOT NULL,
    comprador_id         BIGINT        NOT NULL,
    vendedor_id          BIGINT        NOT NULL,
    valor_final          NUMERIC(14,2) NOT NULL,
    comissao_percentual  NUMERIC(5,2)  NOT NULL,
    comissao_valor       NUMERIC(14,2) NOT NULL,
    vendido_em           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vendas_apartamento UNIQUE (apartamento_id),
    CONSTRAINT uk_vendas_proposta    UNIQUE (proposta_id),
    CONSTRAINT fk_vendas_apartamento FOREIGN KEY (apartamento_id) REFERENCES apartamentos (id),
    CONSTRAINT fk_vendas_proposta    FOREIGN KEY (proposta_id)    REFERENCES propostas (id),
    CONSTRAINT fk_vendas_comprador   FOREIGN KEY (comprador_id)   REFERENCES usuarios (id),
    CONSTRAINT fk_vendas_vendedor    FOREIGN KEY (vendedor_id)    REFERENCES usuarios (id)
);
